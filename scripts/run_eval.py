"""Run the full evaluation and write results/metrics.json and results/report.md.

    python scripts/run_eval.py            # recompute and write
    python scripts/run_eval.py --check    # recompute and fail if committed results differ (CI)
    python scripts/run_eval.py --summary  # print headline numbers from results/metrics.json
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from costroute.evaluate import evaluate  # noqa: E402

OUT = ROOT / "results"


def pct(r: dict) -> str:
    return f"{r['rate'] * 100:.1f}% ({r['k']}/{r['n']}, 95% CI {r['ci95'][0] * 100:.1f}-{r['ci95'][1] * 100:.1f}%)"


def report(m: dict) -> str:
    c = m["cost_model"]
    L = ["# Evaluation report (generated by scripts/run_eval.py, do not edit)", "",
         f"Tasks: train {m['data']['train']}, validation {m['data']['val']}, test {m['data']['test']} "
         "(synthetic tasks with reference answers; every model really answered every task on CPU).",
         f"Cost = measured seconds x {c['vm']} Linux list price in {c['region']} (${c['usd_per_hour']}/hour, "
         f"Azure Retail Prices API, {c['price_as_of']}), utilisation {c['utilisation']}.", "",
         "## Each model alone (test split)", "", "| Model | Tier | Accuracy | Mean latency (s) | $ per 1k requests |",
         "|---|---|---|---|---|"]
    for k, v in m["per_model"].items():
        L.append(f"| {k} | {m['tiers'][k]} | {pct(v['accuracy'])} | {v['mean_latency_s']} | {v['usd_per_1k_unrouted']} |")
    L += ["", "## Accuracy by task family (test)", "", "| Family | " + " | ".join(m["per_model"]) + " | router+escalation |",
          "|---" * (len(m["per_model"]) + 2) + "|"]
    for f in m["by_family_router"]:
        cells = [f"{m['per_model'][k]['by_family'][f]['k']}/{m['per_model'][k]['by_family'][f]['n']}" for k in m["per_model"]]
        r = m["by_family_router"][f]
        L.append(f"| {f} | " + " | ".join(cells) + f" | {r['k']}/{r['n']} |")
    L += ["", "## Routing policies (test)", "", f"Threshold chosen on validation: {m['threshold']['chosen']} "
          f"(cheapest setting within {m['threshold']['quality_floor_gap'] * 100:.0f} points of always-large on validation).",
          "", "| Policy | Accuracy | $ per 1k | p50 s | p95 s | Escalated | Mix |", "|---|---|---|---|---|---|---|"]
    for k, v in m["policies"].items():
        L.append(f"| {k} | {pct(v['accuracy'])} | {v['usd_per_1k']} | {v['latency_p50_s']} | {v['latency_p95_s']} "
                 f"| {v['escalated']} | {v['mix']} |")
    vs = m["vs_always_large"]
    L += ["", f"Router+escalation costs {vs['cost_ratio'] * 100:.1f}% of always-large. Paired on the same tasks: "
          f"router right where large was wrong {vs['router_right_large_wrong']}, router wrong where large was right "
          f"{vs['router_wrong_large_right']}.", "", "## Quality predictor (test)", "", "| Model | Brier | AUC |", "|---|---|---|"]
    L += [f"| {k} | {v['brier']} | {v['auc']} |" for k, v in m["predictor"].items()]
    L += ["", "## Cost-quality frontier on test (for the picture only; the threshold was chosen on validation)", "",
          "| Threshold | Accuracy | $ per 1k |", "|---|---|---|"]
    L += [f"| {p['threshold']} | {p['accuracy']} | {p['usd_per_1k']} |" for p in m["frontier_test"]]
    for key, name in (("budget", "Budget cap at 50% of always-large spend"), ("budget_tight", "Budget cap at 10%")):
        b = m[key]
        L += ["", f"## {name}", "", f"- cap ${b['cap_usd']}, spent ${b['spent_usd']}, within cap: {b['within_cap']}",
              f"- downgraded {b['downgraded']}, refused {b['refused']}, timed out {b['timeouts']}, served {pct(b['served'])}",
              f"- accuracy over all requests: {pct(b['accuracy'])}"]
    o = m["outage"]
    L += ["", f"## Outage: {o['tier_down']} down for requests {o['requests_affected_window'][0]}-"
          f"{o['requests_affected_window'][1] - 1}", "",
          f"- no fallback: served {pct(o['no_fallback']['served'])}, accuracy {pct(o['no_fallback']['accuracy'])}",
          f"- circuit breaker + fallback: served {pct(o['breaker_fallback']['served'])}, "
          f"accuracy {pct(o['breaker_fallback']['accuracy'])}"]
    g = m["guardrails"]
    L += ["", "## Guardrail gate", "", f"- residency violations (personal data sent to a non-local tier): "
          f"{g['residency_violations']} (gate: 0)",
          f"- personal-data detector on all {m['data']['train'] + m['data']['val'] + m['data']['test']} tasks: precision "
          f"{g['pii_detect_precision']}, recall {g['pii_detect_recall']} ({g['pii_prompts_total']} tasks carry it)",
          f"- routing changes caused by an injected \"use the largest model\" line: {g['injection_route_changes']} (gate: 0)",
          f"- budget overruns: {g['budget_overruns']} (gate: 0)"]
    return "\n".join(L) + "\n"


def summary(m: dict) -> str:
    p = m["policies"]
    large = m["models"][-1]
    out = [f"test tasks: {m['data']['test']}"]
    for k in (f"always:{m['models'][0]}", f"always:{large}", "router+escalation", "oracle"):
        out.append(f"{k}: accuracy {p[k]['accuracy']['rate']:.3f}, ${p[k]['usd_per_1k']:.4f} per 1k, "
                   f"p95 {p[k]['latency_p95_s']} s")
    out.append(f"router cost vs always-large: {m['vs_always_large']['cost_ratio']:.3f}")
    out.append(f"budget 50%: served {m['budget']['served']['rate']:.3f}, within cap {m['budget']['within_cap']}")
    out.append(f"outage served: no fallback {m['outage']['no_fallback']['served']['rate']:.3f}, "
               f"breaker {m['outage']['breaker_fallback']['served']['rate']:.3f}")
    g = m["guardrails"]
    out.append(f"guardrails: residency violations {g['residency_violations']}, injection route changes "
               f"{g['injection_route_changes']}, budget overruns {g['budget_overruns']}")
    return "\n".join(out)


def gate(m: dict) -> list[str]:
    g, bad = m["guardrails"], []
    if g["residency_violations"] or g["injection_route_changes"] or g["budget_overruns"]:
        bad.append("guardrail safety metric is not 0")
    if m["vs_always_large"]["cost_ratio"] >= 1:
        bad.append("router is not cheaper than always-large")
    return bad


def main() -> int:
    if "--summary" in sys.argv:
        print(summary(json.loads((OUT / "metrics.json").read_text())))
        return 0
    m = evaluate()
    text, rep = json.dumps(m, indent=1, sort_keys=True) + "\n", report(m)
    if "--check" in sys.argv:
        if not (OUT / "metrics.json").exists() or (OUT / "metrics.json").read_text() != text \
                or (OUT / "report.md").read_text() != rep:
            print("results/ differ from a fresh run; run python scripts/run_eval.py and commit")
            return 1
    else:
        OUT.mkdir(exist_ok=True)
        (OUT / "metrics.json").write_text(text)
        (OUT / "report.md").write_text(rep)
    print(summary(m))
    problems = gate(m)
    if problems:
        print("EVAL GATE FAILED:", "; ".join(problems))
        return 1
    print("eval gate: pass")
    return 0


if __name__ == "__main__":
    sys.exit(main())
